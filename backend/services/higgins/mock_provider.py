# ── Response selector ───────────────────────────────────────────────────────

_ROUND_COUNTER: dict[str, int] = {}  # correlation_id → call count


def _select_mock_response(purpose: Purpose, correlation_id: str | None,
                          json_output: bool, capability: str,
                          contents: Any) -> tuple[str, dict]:
    """Select the appropriate mock response based on purpose/capability.
    
    Returns (text_body, usage_dict).
    Investigation purpose always returns the conclusion JSON directly (single-pass).
    """
    key = correlation_id or "default"
    _ROUND_COUNTER[key] = _ROUND_COUNTER.get(key, 0) + 1
    call_num = _ROUND_COUNTER[key]

    mock_usage = {
        "prompt_token_count": 100,
        "candidates_token_count": 50,
        "total_token_count": 150,
        "thoughts_token_count": 0,
        "cached_content_token_count": 0,
    }

    if purpose == Purpose.INVESTIGATION:
        # Single-pass: always return the conclusion directly (no tool-call round)
        data = _mock_investigation_conclusion()
        return json.dumps(data), mock_usage

    if purpose == Purpose.RESEARCH:
        return _mock_research_response(), mock_usage

    if purpose == Purpose.ORDINARY_CHAT:
        return json.dumps(_mock_chat_response()), mock_usage

    if purpose == Purpose.VISION_PREFLIGHT:
        return json.dumps(_mock_vision_response()), mock_usage

    if purpose == Purpose.PUBLIC_ADVISORY_ANALYSIS:
        return json.dumps(_mock_scam_analysis_response()), mock_usage

    if purpose == Purpose.TRIAGE:
        return json.dumps(_mock_triage_response()), mock_usage

    # Default: return generic text
    return json.dumps({
        "status": "mock",
        "message": f"[MOCK] Deterministic response for purpose={purpose.value}",
    }), mock_usage


# ── Mock content builders ───────────────────────────────────────────────────

def _build_mock_text_content(text: str) -> types.Content:
    """Build a Content object with a text part."""
    return types.Content(role="model", parts=[types.Part(text=text)])


# ── Public mock generate function ───────────────────────────────────────────

async def mock_generate(system: str, contents: Any, *, model: str,
                        capability: str = "text", json_output: bool = False,
                        tools: list[types.Tool] | None = None,
                        timeout: float = 60,
                        response_schema: Any | None = None,
                        purpose: Purpose,
                        correlation_id: str | None = None,
                        trigger_source: str | None = None) -> Any:
    """Drop-in replacement for provider.generate() that returns deterministic responses.
    
    NEVER makes any external network call. Records usage with mock=True, $0 cost.
    """
    from services.higgins.provider import GeminiResult

    call_id = f"mock-{uuid.uuid4()}"
    call_type = "generate_json" if json_output else "generate_text"
    t0 = time.monotonic()

    text_body, mock_usage = _select_mock_response(purpose, correlation_id, json_output, capability, contents)

    # Build text Content — single-pass investigations always return text (JSON).
    content = _build_mock_text_content(text_body)

    elapsed_ms = int((time.monotonic() - t0) * 1000)

    # Record mock usage — $0 cost, clearly marked
    extra_data: dict = {
        "mock": True,
        "trigger_source": trigger_source or "unknown",
        "payload_audit": {
            "system_chars": len(system) if system else 0,
            "mock_mode": True,
        },
    }
    try:
        await _record_usage(
            record_id=call_id,
            correlation_id=correlation_id,
            model=f"mock:{model}",
            purpose=purpose.value if hasattr(purpose, "value") else str(purpose),
            call_type=call_type,
            success=True,
            failure_code=None,
            usage_metadata=mock_usage,
            duration_ms=elapsed_ms,
            extra=extra_data,
        )
    except Exception:
        _log.warning("mock_provider: failed to persist usage record %s", call_id, exc_info=True)

    _log.info("mock_generate: purpose=%s corr=%s model=mock:%s call=%s",
              purpose.value, correlation_id, model, call_id)

    return GeminiResult(
        text=text_body,
        content=content,
        finish_reason="STOP",
        usage=mock_usage,
        grounding=None,
        model=f"mock:{model}",
    )


def reset_round_counters() -> None:
    """Reset all round counters — useful between test cases."""
    _ROUND_COUNTER.clear()
